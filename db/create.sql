-- Here we only create 3 tables for demo purpose.

CREATE TABLE Zipcode (
    zipcode INT NOT NULL PRIMARY KEY,
    city VARCHAR(255) NOT NULL,
    state_id VARCHAR NOT NULL,
    state VARCHAR NOT NULL
);

CREATE TABLE Address_Table (
    address_key INT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    street_num INT NOT NULL,
    street_name VARCHAR(255) NOT NULL,
    zipcode INT NOT NULL
);

CREATE TABLE Users (
    id INT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL CHECK (length(password) >= 8),
    user_ship_address INT NOT NULL REFERENCES Address_Table(address_key),
    user_bill_address INT NOT NULL REFERENCES Address_Table(address_key),
    user_balance DECIMAL(12,2) NOT NULL CHECK(user_balance >= 0.0),
    user_bio VARCHAR(255),
    is_seller BOOLEAN DEFAULT FALSE,
    firstname VARCHAR(255) NOT NULL,
    lastname VARCHAR(255) NOT NULL  
);

CREATE TABLE Product_Category (
    cat_key INT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    cat_name VARCHAR(255) NOT NULL
);

CREATE TABLE Discounts (
    discount_key INT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    discount_amount DECIMAL (4,2) NOT NULL 
);

CREATE TABLE Products (
    product_key INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    seller_key INT NOT NULL REFERENCES Users(id),
    cat_key INT NOT NULL REFERENCES Product_Category(cat_key),
    product_name VARCHAR(255) NOT NULL,
    product_description VARCHAR(255),
    product_price DECIMAL(12,2) NOT NULL CHECK(product_price >= 0.0),
    product_image VARCHAR(255),
    product_discount_code INT REFERENCES Discounts(discount_key),
    available BOOLEAN DEFAULT TRUE,
    product_rating DECIMAL(2,1) CHECK (product_rating BETWEEN 0.0 AND 5.0),
    PRIMARY KEY (product_key, seller_key)
);

CREATE TABLE Inventory (
    product_key INT NOT NULL,
    seller_key INT NOT NULL,
    quantity INT NOT NULL CHECK (quantity >= 0),
    PRIMARY KEY (product_key, seller_key),
    FOREIGN KEY (product_key, seller_key) REFERENCES Products(product_key, seller_key) ON DELETE CASCADE,
    FOREIGN KEY (seller_key) REFERENCES Users(id)
);

CREATE TABLE ProductReviews (
    prod_review_id INT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    product_key INT NOT NULL,
    seller_key INT NOT NULL,
    person_reviewing_id INT NOT NULL,
    review_rating DECIMAL(2,1) NOT NULL DEFAULT 5.0 CHECK (review_rating BETWEEN 0.0 AND 5.0),
    review_description VARCHAR(255),
    review_image VARCHAR(255)
); 

CREATE TABLE UserReviews (
    user_review_id INT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    person_key INT NOT NULL,
    person_reviewing_id INT NOT NULL,
    review_rating DECIMAL(2,1) NOT NULL DEFAULT 5.0 CHECK (review_rating BETWEEN 0.0 AND 5.0),
    review_description VARCHAR(255),
    review_image VARCHAR(255)
); 

CREATE TABLE OrderHistory (
    order_id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    buyer_key INT NOT NULL REFERENCES Users(id),
    seller_key INT NOT NULL,
    product_key INT NOT NULL,
    order_quantity INT NOT NULL CHECK (order_quantity >= 0),
    is_fulfilled BOOLEAN NOT NULL DEFAULT FALSE,
    fulfillment_time timestamp without time zone DEFAULT NULL,
    order_time timestamp without time zone NOT NULL DEFAULT (current_timestamp AT TIME ZONE 'UTC'),
    prod_review_id INT REFERENCES ProductReviews(prod_review_id),
    user_review_id INT REFERENCES UserReviews(user_review_id),
    PRIMARY KEY (order_id, product_key),
    FOREIGN KEY (product_key, seller_key) REFERENCES Products(product_key, seller_key),
    FOREIGN KEY (seller_key) REFERENCES Users(id),
    CHECK ((fulfillment_time IS NULL) OR (order_time <= fulfillment_time))
);

CREATE TABLE Cart (
    cart_item_id INT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    buyer_key INT NOT NULL REFERENCES Users(id),
    product_key INT NOT NULL,
    seller_key INT NOT NULL,
    quantity INT NOT NULL CHECK (quantity > 0),
    price DECIMAL(12,2) NOT NULL,
    total_price DECIMAL(12,2) NOT NULL CHECK (total_price >= 0.0),
    added_to_cart_time TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (current_timestamp AT TIME ZONE 'UTC'),
    FOREIGN KEY (buyer_key) REFERENCES Users(id),
    FOREIGN KEY (product_key, seller_key) REFERENCES Products(product_key, seller_key),
    FOREIGN KEY (seller_key) REFERENCES Users(id)
);


CREATE OR REPLACE FUNCTION calculate_total_price()
RETURNS TRIGGER AS $$
BEGIN
    
    IF NEW.price IS NOT NULL AND NEW.quantity IS NOT NULL THEN
        NEW.total_price = NEW.price * NEW.quantity;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_total_price
BEFORE INSERT OR UPDATE OF price, quantity
ON Cart
FOR EACH ROW
EXECUTE FUNCTION calculate_total_price();
